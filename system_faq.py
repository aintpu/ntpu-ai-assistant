def _normalize(text: str) -> str:
    text = str(text or "").strip().lower()
    return re.sub(r"[^a-z0-9\u4e00-\u9fff]+", "", text)


def _features(text: str) -> set[str]:
    lowered = str(text or "").lower()
    result = set(re.findall(r"[a-z0-9]+", lowered))
    for segment in re.findall(r"[\u4e00-\u9fff]+", lowered):
        if len(segment) == 1:
            result.add(segment)
        else:
            result.update(segment[i:i + 2] for i in range(len(segment) - 1))
    return result


def detect_language(query: str) -> str:
    """Return the response language expected by the SYSTEM FAQ."""
    return "zh-TW" if re.search(r"[\u4e00-\u9fff]", query or "") else "en"


def _has_any(text: str, phrases: tuple[str, ...]) -> bool:
    lowered = str(text or "").lower()
    return any(phrase in lowered for phrase in phrases)


class SystemFAQRetriever:
    def __init__(self, content_path: str | Path = DEFAULT_CONTENT_PATH):
        self.content_path = Path(content_path)
        with self.content_path.open("r", encoding="utf-8") as handle:
            content = json.load(handle)
        faqs = content.get("faqs") if isinstance(content, dict) else None
        if not isinstance(faqs, list) or len(faqs) < 15:
            raise ValueError("SYSTEM FAQ content must contain at least 15 entries")
        self.content = content
        self.faqs = faqs

    @staticmethod
    def _score(query: str, faq: dict[str, Any]) -> tuple[float, bool]:
        q_norm = _normalize(query)
        q_features = _features(query)
        phrases = [
            faq.get("question_zh", ""),
            faq.get("question_en", ""),
            *(faq.get("aliases_zh") or []),
            *(faq.get("aliases_en") or []),
        ]
        best = 0.0
        exact = False
        for phrase in phrases:
            p_norm = _normalize(phrase)
            if not p_norm:
                continue
            if q_norm == p_norm:
                return 1.0, True
            if min(len(q_norm), len(p_norm)) >= 4 and (q_norm in p_norm or p_norm in q_norm):
                containment = min(len(q_norm), len(p_norm)) / max(len(q_norm), len(p_norm))
                best = max(best, 0.82 + 0.14 * containment)
            p_features = _features(phrase)
            overlap = len(q_features & p_features)
            if overlap:
                coverage = overlap / max(1, len(q_features))
                candidate_coverage = overlap / max(1, len(p_features))
                jaccard = overlap / max(1, len(q_features | p_features))
                best = max(best, 0.48 * coverage + 0.34 * candidate_coverage + 0.18 * jaccard)

        keyword_features = _features(" ".join(str(x) for x in faq.get("keywords", [])))
        keyword_overlap = len(q_features & keyword_features)
        if keyword_overlap:
            keyword_coverage = keyword_overlap / max(1, len(q_features))
            best = max(best, 0.58 * keyword_coverage + 0.18)
        # Capability questions often contain a variable office/topic name
        # (for example, "你有語言中心免修的資料嗎").  Route the intent to the
        # capability FAQ without teaching the lexical retriever every topic.
        if faq.get("id") == "system-capabilities" and _has_any(query, _CAPABILITY_CUES):
            best = max(best, 0.76)
        return min(1.0, best), exact

    def search(self, query: str, top_k: int = 3) -> list[SystemFAQMatch]:
        matches = []
        for faq in self.faqs:
            score, exact = self._score(query, faq)
            matches.append(SystemFAQMatch(str(faq["id"]), score, exact, faq))
        matches.sort(key=lambda item: item.score, reverse=True)
        return matches[:max(1, int(top_k))]

    def best(self, query: str) -> SystemFAQMatch:
        return self.search(query, top_k=1)[0]


def should_route_system(
    query: str,
    match: SystemFAQMatch,
    *,
    threshold: float,
) -> bool:
    """Conservatively classify explicit questions about the assistant itself."""
    if match.score < threshold:
        return False
    has_system_cue = _has_any(query, _SYSTEM_CUES)
    if match.exact and (has_system_cue or _has_any(query, _CAPABILITY_CUES)):
        return True
    if not has_system_cue:
        return False

    # Office-detail questions must keep using the seven-office RAG unless the user
    # is explicitly asking whether the system has/supports that information.
    if _has_any(query, _OFFICE_CONTENT_CUES) and not _has_any(query, _CAPABILITY_CUES):
        return False
    return True


def should_use_system_fallback(
    query: str,
    match: SystemFAQMatch,
    *,
    threshold: float,
) -> bool:
    """Apply a stricter SYSTEM match after the ordinary router says OTHER."""
    if match.score < threshold:
        return False
    if match.exact:
        return True
    if _has_any(query, _OFFICE_CONTENT_CUES) and not _has_any(query, _CAPABILITY_CUES):
        return False
    return _has_any(query, _SYSTEM_CUES)

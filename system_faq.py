"""Deterministic SYSTEM FAQ routing and retrieval.

The module has no FastAPI, LangChain, or model-provider dependency so the
SYSTEM domain can be tested without building the seven-office FAISS index.  FAQ
answers are extractive-first: a matched answer is returned verbatim from the
shared structured content file instead of being regenerated by an LLM.
"""


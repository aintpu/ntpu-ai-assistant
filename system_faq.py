class QueryDomain(str, Enum):
    SYSTEM = "SYSTEM"
    OPE = "OPE"
    GE = "GE"
    LC = "LC"
    OAA = "OAA"
    OSA = "OSA"
    HR = "HR"
    OGA = "OGA"
    OTHER = "OTHER"


@dataclass(frozen=True)
class SystemFAQMatch:
    faq_id: str
    score: float
    exact: bool
    faq: dict[str, Any]

    def answer(self, language: str = "zh-TW") -> str:
        return str(self.faq["answer_en" if language.lower().startswith("en") else "answer_zh"])

    def source(self, language: str = "zh-TW") -> dict[str, str]:
        raw = self.faq["source"]
        return {
            "type": "system",
            "title": str(raw["title_en" if language.lower().startswith("en") else "title_zh"]),
            "url": str(raw["url"]),
            "faq_id": self.faq_id,
        }


